def derived() -> dict:
    """Quantities computed from the REAL anchors."""
    implied_rail_fare_rev = PT_FUND_CONTRIBUTION_M / PT_FUND_SHARE / FARE_INCREASE_2026
    boardings_m = (MRT_DAILY_K[2025] + LRT_DAILY_K_2025) * 365 / 1000.0
    other = SBS_2025_M["total"] - SBS_2025_M["staff"] - SBS_2025_M["maintenance"] - SBS_2025_M["energy"]
    base = MRT_DAILY_K[2019]
    return {
        "implied_rail_fare_revenue_m": implied_rail_fare_rev,
        "rail_boardings_m": boardings_m,
        "fare_per_boarding": implied_rail_fare_rev / boardings_m,
        "line_trips_m": DTL_DAILY_2025 * 365 / 1e6,
        "cost_shares": {"staff": SBS_2025_M["staff"] / SBS_2025_M["total"],
                        "maintenance": SBS_2025_M["maintenance"] / SBS_2025_M["total"],
                        "energy": SBS_2025_M["energy"] / SBS_2025_M["total"],
                        "other": other / SBS_2025_M["total"]},
        "pandemic_path": [MRT_DAILY_K[y] / base for y in (2020, 2021, 2022, 2023)],
        "sbs_group_margin": SBS_2025_M["operating_profit"] / SBS_2025_M["revenue"],
    }


