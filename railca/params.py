def check_anchor_ids() -> None:
    """Fail loudly if a fact id used above is missing from the fact base."""
    facts = factbase.by_id()
    for fid in ("F22", "F23", "F38", "F39", "F40", "F41", "F42", "F45", "F46", "F50", "F51", "F52", "F53",
                "F54", "F55", "F62", "F64", "F69", "F75", "F76", "F77", "F80", "F81"):
        if fid not in facts:
            raise KeyError(fid)
