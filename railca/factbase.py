"""Read data/facts.csv and render it as a readable Markdown fact base."""
from __future__ import annotations

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FACTS = ROOT / "data" / "facts.csv"
FIELDS = ["id", "topic", "claim", "value", "as_of", "source_url", "publisher", "source_type", "accessed",
          "quote", "status", "note"]


def load() -> list[dict]:
    with FACTS.open(encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def by_id() -> dict[str, dict]:
    return {r["id"]: r for r in load()}


def counts() -> dict:
    rows = load()
    return {
        "n_facts": len(rows),
        "n_verified": sum(r["status"] == "VERIFIED" for r in rows),
        "n_unverified": sum(r["status"] == "UNVERIFIED" for r in rows),
        "n_conflicts": sum("CONFLICT" in r["note"] for r in rows),
        "n_sources": len({r["source_url"] for r in rows}),
    }


def render() -> str:
    rows = load()
    c = counts()
    out = ["# Fact base", "",
           "<!-- Generated by scripts/build_docs.py from data/facts.csv. Edit the CSV, not this file. -->", "",
           f"{c['n_facts']} facts from {c['n_sources']} sources, all accessed on {rows[0]['accessed']}. "
           f"{c['n_verified']} are VERIFIED: the quoted passage was found in a primary source (an authority, "
           f"a ministry, a regulator, an operator or an exchange filing) when the page was re-opened by "
           f"`scripts/verify_facts.py`. {c['n_unverified']} are UNVERIFIED: press reports, or statements that "
           f"nothing was found. {c['n_conflicts']} rows carry a CONFLICT note where sources disagree or a later "
           f"statement supersedes an earlier one.", "",
           "Quotes are short extracts for verification. Follow the link for the full context.", ""]
    topics: list[str] = []
    for r in rows:
        if r["topic"] not in topics:
            topics.append(r["topic"])
    for t in topics:
        out += [f"## {t}", ""]
        for r in (x for x in rows if x["topic"] == t):
            out.append(f"**{r['id']} ({r['status']})** {r['claim']}.")
            out.append(f"- Value: {r['value']}. As of: {r['as_of']}.")
            out.append(f"- Source: [{r['publisher']}]({r['source_url']})")
            if r["quote"]:
                out.append(f"- Quote: \"{r['quote']}\"")
            if r["note"]:
                out.append(f"- Note: {r['note']}")
            out.append("")
    return "\n".join(out).rstrip() + "\n"
